from __future__ import annotations

from pathlib import Path
from typing import Callable

import cv2
import numpy as np
import pandas as pd

from PySide6.QtCore import Qt
from PySide6.QtWidgets import (
    QDialog,
    QVBoxLayout,
    QLabel,
    QTabWidget,
    QMessageBox,
    QSizePolicy,
)

from .edit_points_dialog import EditPointsDialog
from .view3d_dialog import Edit3DDialog, QTimer, _uv_from_surface_point, _uv_to_px


class LandmarkValidationDialog(QDialog):
    """Combined 2D/3D landmark validation dialog.

    The 3D CSV is the authoritative landmark set. The 2D tab can work either on
    the original texture coordinates or, when available, on the auxiliary
    SmartUV-baked texture generated by Blender. In SmartUV mode the 2D editor is
    deletion-only: the visible points are projections of the current 3D rows on
    the SmartUV texture, and removing them removes the corresponding 3D rows.
    """

    def __init__(
        self,
        *,
        texture_path: Path,
        obj_path: Path,
        csv2d_path: Path,
        csv3d_path: Path,
        apply_2d_changes: Callable[[pd.DataFrame], dict],
        v_flip: bool = True,
        snap_to_vertices: bool = True,
        parent=None,
        smartuv_texture_path: Path | None = None,
        smartuv_obj_path: Path | None = None,
    ):
        super().__init__(parent)
        self.setWindowTitle("2D/3D Landmark Validation")
        self.resize(1280, 920)

        QTimer.singleShot(0, self.showMaximized)

        self.texture_path = Path(texture_path)
        self.obj_path = Path(obj_path)
        self.csv2d_path = Path(csv2d_path)
        self.csv3d_path = Path(csv3d_path)
        self.apply_2d_changes = apply_2d_changes
        self.v_flip = bool(v_flip)
        self.snap_to_vertices = bool(snap_to_vertices)

        self.smartuv_texture_path = Path(smartuv_texture_path) if smartuv_texture_path else None
        self.smartuv_obj_path = Path(smartuv_obj_path) if smartuv_obj_path else None
        self._use_smartuv_2d = bool(
            self.smartuv_texture_path
            and self.smartuv_obj_path
            and self.smartuv_texture_path.exists()
            and self.smartuv_obj_path.exists()
        )
        self._smartuv_mesh = None
        self._smartuv_tex_size: tuple[int, int] | None = None

        self._current_tab = 0
        self._visited_3d = False
        self._2d_dirty = False
        self._closing = False
        self._initial_df2d = self._read_csv_snapshot(self.csv2d_path)
        self._initial_df3d = self._read_csv_snapshot(self.csv3d_path)

        self._build_ui()

    @staticmethod
    def _read_csv_snapshot(path: Path) -> pd.DataFrame:
        try:
            path = Path(path)
            if path.exists():
                return pd.read_csv(path).reset_index(drop=True)
        except Exception:
            pass
        return pd.DataFrame()

    def _build_ui(self):
        outer = QVBoxLayout(self)
        outer.setContentsMargins(12, 12, 12, 12)
        outer.setSpacing(10)

        title = QLabel("2D/3D Validation")
        title.setStyleSheet("font-size: 18px; font-weight: 700;")
        outer.addWidget(title)

        if self._use_smartuv_2d:
            subtitle_text = (
                "Validate the same landmark set from the SmartUV texture preview and from the 3D model. "
                "The 2D tab is deletion-only; every removed SmartUV point removes the corresponding 3D landmark."
            )
        else:
            subtitle_text = (
                "Validate the same landmark set from the texture and from the 3D model. "
                "Changes are synchronized when switching tabs and when continuing."
            )
        subtitle = QLabel(subtitle_text)
        subtitle.setProperty("role", "subtitle")
        subtitle.setWordWrap(True)
        outer.addWidget(subtitle)

        self.status_label = QLabel("")
        self.status_label.setWordWrap(True)
        self.status_label.setStyleSheet("color: #444;")
        outer.addWidget(self.status_label)

        self.tabs = QTabWidget()
        self.tabs.setDocumentMode(True)
        outer.addWidget(self.tabs, 1)

        if self._use_smartuv_2d:
            try:
                df2d = self._build_smartuv_2d_from_3d()
                texture_for_2d = self.smartuv_texture_path
            except Exception as e:
                self._use_smartuv_2d = False
                QMessageBox.warning(
                    self,
                    "SmartUV 2D validation",
                    "Could not project the 3D landmarks onto the SmartUV texture. "
                    f"The editor will fall back to the original 2D texture.\n\n{e}",
                )
                df2d = self._load_2d_from_disk()
                texture_for_2d = self.texture_path
        else:
            df2d = self._load_2d_from_disk()
            texture_for_2d = self.texture_path

        self.editor2d = EditPointsDialog(
            texture_path=texture_for_2d,
            df2d=df2d,
            parent=self,
            allow_add_points=False,
        )
        self.editor2d.setWindowFlags(Qt.Widget)
        self.editor2d.setSizePolicy(QSizePolicy.Expanding, QSizePolicy.Expanding)
        self.editor2d.set_apply_callback(self.accept, text="Continue (ENTER)")
        self.editor2d.set_cancel_callback(self.reject)
        self.editor2d.changed.connect(self._mark_2d_dirty)

        self.editor3d = Edit3DDialog(
            obj_path=self.obj_path,
            texture_path=self.texture_path,
            csv2d_path=self.csv2d_path,
            csv3d_path=self.csv3d_path,
            v_flip=self.v_flip,
            snap_to_vertices=self.snap_to_vertices,
            parent=self,
        )
        self.editor3d.setWindowFlags(Qt.Widget)
        self.editor3d.setSizePolicy(QSizePolicy.Expanding, QSizePolicy.Expanding)
        self.editor3d.set_continue_callback(self.accept, text="Continue (ENTER)")
        self.editor3d.set_cancel_callback(self.reject)

        self.tabs.addTab(self.editor2d, "2D SmartUV Validation" if self._use_smartuv_2d else "2D Texture Validation")
        self.tabs.addTab(self.editor3d, "3D Model Validation")
        self.tabs.currentChanged.connect(self._on_tab_changed)

        if self._use_smartuv_2d:
            self._refresh_status("Ready. The 2D tab shows the SmartUV-baked texture; use it only to remove landmarks.")
        else:
            self._refresh_status("Ready. Start in 2D or switch to 3D when needed.")

    def _mark_2d_dirty(self):
        self._2d_dirty = True
        self._refresh_status("2D changes pending. They will be synchronized with 3D when you switch tabs or continue.")

    def _refresh_status(self, text: str):
        self.status_label.setText(text)

    def _reset_to_initial_landmarks(self):
        self._initial_df3d.to_csv(self.csv3d_path, index=False)
        self._initial_df2d.to_csv(self.csv2d_path, index=False)
        self._2d_dirty = False

        if hasattr(self, "editor3d"):
            self.editor3d.undo_stack.clear()
            self.editor3d.refresh_visuals_from_df(self._initial_df3d)

        if hasattr(self, "editor2d"):
            try:
                df2d = self._current_2d_reference()
            except Exception:
                df2d = self._initial_df2d.copy().reset_index(drop=True)
            self.editor2d.set_result_df(df2d, reset_start=True, emit_changed=False)
        else:
            df2d = self._initial_df2d.copy().reset_index(drop=True)

        self._refresh_status(
            f"Reset complete. Initial landmarks restored. "
            f"2D points: {len(df2d)} | 3D points: {len(self._initial_df3d)}"
        )

    def _load_2d_from_disk(self) -> pd.DataFrame:
        if not self.csv2d_path.exists():
            return pd.DataFrame(columns=["pixel_x", "pixel_y", "area", "contour_id"])
        return pd.read_csv(self.csv2d_path)

    def _load_3d_from_disk(self) -> pd.DataFrame:
        if not self.csv3d_path.exists():
            return pd.DataFrame()
        return pd.read_csv(self.csv3d_path)

    @staticmethod
    def _same_2d_points(a: pd.DataFrame, b: pd.DataFrame) -> bool:
        preferred = ["source_row_idx", "pixel_x", "pixel_y", "area", "contour_id"]
        cols = [c for c in preferred if c in a.columns and c in b.columns]
        if not cols:
            cols = [c for c in ["pixel_x", "pixel_y"] if c in a.columns and c in b.columns]
        if not cols:
            return len(a) == len(b)
        aa = a[cols].reset_index(drop=True).copy()
        bb = b[cols].reset_index(drop=True).copy()
        return aa.equals(bb)

    def _parse_obj_for_projection(self, path: Path):
        def _norm_idx(idx: int, n: int) -> int:
            return idx - 1 if idx > 0 else n + idx

        V, VT, Fv, Fvt = [], [], [], []
        with open(path, "r", encoding="utf-8", errors="ignore") as f:
            for raw in f:
                line = raw.strip()
                if not line or line.startswith("#"):
                    continue
                if line.startswith("v "):
                    parts = line.split()
                    if len(parts) >= 4:
                        V.append([float(parts[1]), float(parts[2]), float(parts[3])])
                elif line.startswith("vt "):
                    parts = line.split()
                    if len(parts) >= 3:
                        VT.append([float(parts[1]), float(parts[2])])
                elif line.startswith("f "):
                    parts = line.split()[1:]
                    vidx, vtidx = [], []
                    for part in parts:
                        comps = part.split("/")
                        if not comps or comps[0] == "":
                            continue
                        vidx.append(_norm_idx(int(comps[0]), len(V)))
                        if len(comps) > 1 and comps[1] != "":
                            vtidx.append(_norm_idx(int(comps[1]), len(VT)))
                    if len(vidx) >= 3 and len(vtidx) >= 3:
                        for i in range(1, len(vidx) - 1):
                            Fv.append([vidx[0], vidx[i], vidx[i + 1]])
                            Fvt.append([vtidx[0], vtidx[i], vtidx[i + 1]])

        V = np.asarray(V, dtype=np.float32)
        VT = np.asarray(VT, dtype=np.float32)
        Fv = np.asarray(Fv, dtype=np.int32)
        Fvt = np.asarray(Fvt, dtype=np.int32)
        if V.size == 0 or VT.size == 0 or Fv.size == 0 or Fvt.size == 0:
            raise ValueError(f"OBJ does not contain enough geometry/UV data: {path}")

        tri_v = V[Fv]
        tri_uv = VT[Fvt]
        tri_centroids = tri_v.mean(axis=1)
        return {
            "V": V,
            "VT": VT,
            "Fv": Fv,
            "Fvt": Fvt,
            "tri_v": tri_v,
            "tri_uv": tri_uv,
            "tri_centroids": tri_centroids,
        }

    def _ensure_smartuv_projection_cache(self):
        if not self._use_smartuv_2d:
            raise RuntimeError("SmartUV 2D validation is not enabled.")
        if self._smartuv_mesh is None:
            smart = self._parse_obj_for_projection(self.smartuv_obj_path)
            # The exported SmartUV OBJ contains the new UV layout. The original
            # CSV points, however, belong to the original 3D model. When face
            # order matches, combine original geometry with SmartUV UVs; this
            # makes the projection resilient to Blender import/export transforms.
            try:
                original = self._parse_obj_for_projection(self.obj_path)
                if original["Fv"].shape[0] == smart["Fvt"].shape[0]:
                    tri_v = original["V"][original["Fv"]]
                    tri_uv = smart["VT"][smart["Fvt"]]
                    smart["tri_v"] = tri_v
                    smart["tri_uv"] = tri_uv
                    smart["tri_centroids"] = tri_v.mean(axis=1)
            except Exception:
                pass
            self._smartuv_mesh = smart
        if self._smartuv_tex_size is None:
            img = cv2.imread(str(self.smartuv_texture_path), cv2.IMREAD_COLOR)
            if img is None:
                raise FileNotFoundError(f"Could not read SmartUV texture: {self.smartuv_texture_path}")
            h, w = img.shape[:2]
            self._smartuv_tex_size = (int(w), int(h))

    def _row_xyz(self, row: pd.Series) -> np.ndarray | None:
        for cols in (("x3d", "y3d", "z3d"), ("X", "Y", "Z"), ("x3d_raw", "y3d_raw", "z3d_raw")):
            if all(c in row.index for c in cols):
                vals = pd.to_numeric(pd.Series([row[cols[0]], row[cols[1]], row[cols[2]]]), errors="coerce").to_numpy(dtype=float)
                if np.isfinite(vals).all():
                    return vals.astype(np.float32)
        return None

    def _build_smartuv_2d_from_3d(self) -> pd.DataFrame:
        self._ensure_smartuv_projection_cache()
        df3d = self._load_3d_from_disk().reset_index(drop=True)
        if df3d.empty:
            return pd.DataFrame(columns=["pixel_x", "pixel_y", "area", "contour_id", "source_row_idx"])

        W, H = self._smartuv_tex_size
        mesh = self._smartuv_mesh
        rows = []
        for idx, row in df3d.iterrows():
            p = self._row_xyz(row)
            if p is None:
                continue
            uv, _xyz = _uv_from_surface_point(
                p,
                tri_v=mesh["tri_v"],
                tri_uv=mesh["tri_uv"],
                tri_centroids=mesh["tri_centroids"],
                k=160,
            )
            if uv is None or not np.isfinite(uv).all():
                continue
            px, py = _uv_to_px(float(uv[0]), float(uv[1]), W, H, v_flip=self.v_flip)
            rows.append({
                "pixel_x": int(px),
                "pixel_y": int(py),
                "area": float(row.get("area", 0.0)) if pd.notna(row.get("area", 0.0)) else 0.0,
                "contour_id": int(row.get("contour_id", -1)) if pd.notna(row.get("contour_id", -1)) else -1,
                "source_row_idx": int(idx),
                "original_pixel_x": int(row.get("pixel_x", 0)) if pd.notna(row.get("pixel_x", 0)) else 0,
                "original_pixel_y": int(row.get("pixel_y", 0)) if pd.notna(row.get("pixel_y", 0)) else 0,
            })

        return pd.DataFrame(rows)

    def _build_original_2d_from_3d(self, df3d: pd.DataFrame) -> pd.DataFrame:
        if df3d is None or df3d.empty:
            return pd.DataFrame(columns=["pixel_x", "pixel_y", "area", "contour_id"])

        df2d = pd.DataFrame(index=df3d.index)
        df2d["pixel_x"] = pd.to_numeric(df3d.get("pixel_x"), errors="coerce").fillna(0).astype(int) if "pixel_x" in df3d.columns else 0
        df2d["pixel_y"] = pd.to_numeric(df3d.get("pixel_y"), errors="coerce").fillna(0).astype(int) if "pixel_y" in df3d.columns else 0
        df2d["area"] = pd.to_numeric(df3d.get("area"), errors="coerce").fillna(0.0) if "area" in df3d.columns else 0.0
        df2d["contour_id"] = pd.to_numeric(df3d.get("contour_id"), errors="coerce").fillna(-1).astype(int) if "contour_id" in df3d.columns else -1
        return df2d.reset_index(drop=True)

    def _sync_smartuv_2d_deletions_to_3d(self, df_current: pd.DataFrame) -> dict:
        if "source_row_idx" not in df_current.columns:
            raise RuntimeError("SmartUV 2D table does not contain source_row_idx.")

        df3d_before = self._load_3d_from_disk().reset_index(drop=True)
        valid_idx = pd.to_numeric(df_current["source_row_idx"], errors="coerce").dropna().astype(int)
        keep = set(int(v) for v in valid_idx.to_list())
        keep = {i for i in keep if 0 <= i < len(df3d_before)}

        df3d_after = df3d_before.iloc[sorted(keep)].reset_index(drop=True) if keep else df3d_before.iloc[0:0].copy()
        df2d_after = self._build_original_2d_from_3d(df3d_after)

        df3d_after.to_csv(self.csv3d_path, index=False)
        df2d_after.to_csv(self.csv2d_path, index=False)

        n2d = int(len(df2d_after))
        n3d = int(len(df3d_after))
        return {"csv_2d": str(self.csv2d_path), "csv_3d": str(self.csv3d_path), "n_2d": n2d, "n_3d": n3d}

    def _current_2d_reference(self) -> pd.DataFrame:
        if self._use_smartuv_2d:
            return self._build_smartuv_2d_from_3d().reset_index(drop=True)
        return self._load_2d_from_disk().reset_index(drop=True)

    def _sync_2d_to_3d(self) -> bool:
        df_current = self.editor2d.get_result_df().copy().reset_index(drop=True)

        try:
            df_reference = self._current_2d_reference()
        except Exception:
            df_reference = pd.DataFrame()

        if (not self._2d_dirty) and self._same_2d_points(df_current, df_reference):
            return True

        try:
            self._refresh_status("Synchronizing 2D changes with the 3D model…")
            if self._use_smartuv_2d:
                result = self._sync_smartuv_2d_deletions_to_3d(df_current)
            else:
                result = self.apply_2d_changes(df_current)
            self._2d_dirty = False
            if hasattr(self, "editor3d"):
                self.editor3d.refresh_from_disk()
            n2d = result.get("n_2d", len(df_current)) if isinstance(result, dict) else len(df_current)
            n3d = result.get("n_3d", "—") if isinstance(result, dict) else "—"
            self._refresh_status(f"Synchronized. 2D points: {n2d} | 3D points: {n3d}")
            return True
        except Exception as e:
            QMessageBox.warning(self, "2D/3D synchronization", f"Could not synchronize 2D changes with 3D:\n{e}")
            self._refresh_status("Synchronization failed. Review the 2D changes before continuing.")
            return False

    def _refresh_2d_from_disk(self):
        try:
            df2d = self._current_2d_reference()
            self.editor2d.set_result_df(df2d, reset_start=True, emit_changed=False)
            self._2d_dirty = False
            if self._use_smartuv_2d:
                self._refresh_status(f"SmartUV 2D view refreshed from the current 3D landmark set. Points: {len(df2d)}")
            else:
                self._refresh_status(f"2D view refreshed from the current 3D landmark set. Points: {len(df2d)}")
        except Exception as e:
            QMessageBox.warning(self, "Refresh 2D", f"Could not refresh 2D points from disk:\n{e}")

    def _on_tab_changed(self, index: int):
        previous = self._current_tab
        self._current_tab = int(index)

        if previous == 0 and index == 1:
            if not self._sync_2d_to_3d():
                self.tabs.blockSignals(True)
                self.tabs.setCurrentIndex(0)
                self.tabs.blockSignals(False)
                self._current_tab = 0
                return
            self.editor3d.refresh_from_disk()
            self._visited_3d = True

        elif previous == 1 and index == 0:
            # 3D edits are persisted immediately by the 3D editor. Reload the 2D
            # tab so both views represent the same landmark set.
            self.editor3d.refresh_from_disk()
            self._refresh_2d_from_disk()

    def accept(self):
        if self._closing:
            return
        if self.tabs.currentIndex() == 0:
            if not self._sync_2d_to_3d():
                return
            if not self._visited_3d:
                self.tabs.blockSignals(True)
                self.tabs.setCurrentIndex(1)
                self.tabs.blockSignals(False)
                self._current_tab = 1
                self._visited_3d = True
                self.editor3d.refresh_from_disk()
                self._refresh_status("2D changes synchronized. Review the 3D model before continuing.")
                return
        else:
            self._visited_3d = True
            self.editor3d.refresh_from_disk()
            self._refresh_2d_from_disk()

        self._closing = True
        super().accept()

    def reject(self):
        if self._closing:
            return
        try:
            self._initial_df3d.to_csv(self.csv3d_path, index=False)
            self._initial_df2d.to_csv(self.csv2d_path, index=False)
        except Exception as e:
            QMessageBox.warning(self, "Cancel validation", f"Could not restore the initial landmark files:\n{e}")
            return
        self._2d_dirty = False
        self._closing = True
        super().reject()

    def closeEvent(self, event):
        # Match the previous editors: closing the window applies the current state.
        if not self._closing:
            if self.tabs.currentIndex() == 0 and not self._sync_2d_to_3d():
                event.ignore()
                return
            if self.tabs.currentIndex() == 1:
                self.editor3d.refresh_from_disk()
                self._refresh_2d_from_disk()
            self._closing = True
            super().accept()
        event.accept()
