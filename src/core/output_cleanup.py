def _safe_unlink(path: Path) -> bool:
    try:
        if path.exists() and path.is_file():
            path.unlink()
            return True
    except Exception:
        return False
    return False


def _safe_move(src: Path, dst: Path) -> Path | None:
    try:
        if not src.exists() or not src.is_file():
            return None
        dst.parent.mkdir(parents=True, exist_ok=True)
        if dst.exists():
            stem = dst.stem
            suffix = dst.suffix
            i = 1
            while True:
                candidate = dst.with_name(f"{stem}_{i}{suffix}")
                if not candidate.exists():
                    dst = candidate
                    break
                i += 1
        shutil.move(str(src), str(dst))
        return dst
    except Exception:
        return None


def cleanup_legacy_output_clutter(out_dir: str | Path) -> None:
    """Clean redundant files generated by older versions without touching core workflow files.

    The root output folder should keep only the files needed to reopen or continue
    the workflow. Debug/temporary files are moved to `_processing` or removed when
    an equivalent final file already exists in `results`.
    """
    root = Path(out_dir)
    if not root.exists():
        return

    openpose = processing_dir(root, "openpose", create=False)
    backups = processing_dir(root, "backups", create=False)
    processing = processing_dir(root, create=False)
    detections = detections_dir(root, create=False)
    scenes = scenes_dir(root, create=False)

    # Old rigging intermediates used to be written in the project root. They are
    # not required for Open Project and make the folder noisy, so move them to a
    # private processing folder if they exist.
    for name in (
        "hand_openpose.png",
        "hand_openpose_keypoints_overlay.png",
        "openpose_hand_keypoints_2d.csv",
        "hand_joints_3d.csv",
    ):
        _safe_move(root / name, openpose / name)

    # Old backups should not remain mixed with the project files.
    for bak in root.glob("detections_labeled.csv.bak_*"):
        _safe_move(bak, backups / bak.name)

    # Old temporary editor CSVs are superseded by detections_labeled.csv.
    _safe_unlink(root / "detections_labeled_corrected.csv")

    # Remove temporary write files that may remain after interrupted CSV exports.
    for tmp in root.glob("*.tmp"):
        _safe_unlink(tmp)

    # The detailed result is now XLSX-only. Remove stale CSV copies produced by
    # older versions so users do not confuse them with current output.
    _safe_unlink(root / "hand_measures_detailed.csv")
    _safe_unlink(root / "hand_measures_wide.csv")
    _safe_unlink(root / "points_xyz.csv")

    # Newer versions store final measure CSVs in results/. If older duplicate
    # copies exist in the root and the final result exists, remove the duplicate.
    # New canonical workflow files live below _processing. If duplicates remain
    # from older runs in the output root and the canonical file exists, remove
    # only the duplicate.
    for name in ("detections_all.csv", "detections_mapped_3d.csv", "detections_labeled.csv"):
        if (detections / name).exists():
            _safe_unlink(root / name)

    for name in (
        "hand_rigged.blend",
        "hand_rigged_labeled.blend",
        "hand_rigged_labeled_final.blend",
        "hand_rigged_labeled_manual.blend",
        "hand_with_points.obj",
        "hand_with_points.mtl",
    ):
        if (scenes / name).exists():
            _safe_unlink(root / name)

    for name in ("project_context.json", "target_ranges.json", "LandmarksOperations_selected.csv"):
        if (processing / name).exists():
            _safe_unlink(root / name)

    results = results_dir(root, create=False)
    if results.exists():
        _safe_unlink(results / "hand_measures_detailed.csv")
        _safe_unlink(results / "hand_measures_wide.csv")
        _safe_unlink(results / "points_xyz.csv")
        for name in ("hand_measures_detailed.xlsx", "points_xyz.xlsx", "hand_rigged_labeled.blend"):
            root_file = root / name
            result_file = results / name
            if root_file.exists() and result_file.exists():
                _safe_unlink(root_file)

    # Drop empty private folders left after temporary files have been consumed.
    for folder in (
        root / PROCESSING_DIR_NAME / "label_editor",
        backups,
        openpose,
        root / PROCESSING_DIR_NAME / THRESHOLD_PREVIEW_DIR_NAME,
        detections,
        scenes,
        root / PROCESSING_DIR_NAME,
    ):
        try:
            if folder.exists() and folder.is_dir() and not any(folder.iterdir()):
                folder.rmdir()
        except Exception:
            pass
